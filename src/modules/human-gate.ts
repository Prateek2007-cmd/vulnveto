/**
 * human-gate (Remediate lane)
 *
 * The ONLY writer in the system. Nothing here runs without explicit human
 * approval — the CLI prompts per fix, and this module only executes what
 * was approved. Currently supports: npm version-bump fixes applied as
 * DRAFT pull requests via the GitHub API.
 *
 * Requires GITHUB_TOKEN with repo scope (fine-grained: contents + PRs write).
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { Finding, RepoInventory } from "../contracts.js";

export interface AppliedFix {
  findingId: string;
  prUrl: string;
  branch: string;
}

function githubToken(): string {
  const t = process.env.GITHUB_TOKEN;
  if (!t) throw new Error("GITHUB_TOKEN is not set — cannot open a draft PR without it.");
  return t;
}

function parseRepo(url: string): { owner: string; repo: string } {
  const m = url.match(/^https:\/\/github\.com\/([\w.-]+)\/([\w.-]+?)(\.git)?\/?$/);
  if (!m) throw new Error(`Cannot parse GitHub repo URL: ${url}`);
  return { owner: m[1], repo: m[2] };
}

async function gh(token: string, method: string, path: string, body?: unknown) {
  const res = await fetch(`https://api.github.com${path}`, {
    method,
    headers: {
      accept: "application/vnd.github+json",
      authorization: `Bearer ${token}`,
      "content-type": "application/json",
      "user-agent": "vulnveto/0.1.0",
    },
    body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(30_000),
  });
  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new Error(`GitHub API ${method} ${path} → ${res.status}: ${text.slice(0, 200)}`);
  }
  return res.json();
}

/**
 * Apply an approved npm "bump" fix as a draft PR.
 * Steps: branch from default → bump version in package.json → commit → draft PR.
 */
export async function applyBumpAsDraftPR(
  inv: RepoInventory,
  finding: Finding
): Promise<AppliedFix> {
  const token = githubToken();
  const { owner, repo } = parseRepo(inv.repoUrl);
  const action = finding.fix?.action as
    | { type: string; package?: string; to?: string }
    | undefined;
  if (!action || action.type !== "bump" || !action.package || !action.to) {
    throw new Error("human-gate: finding has no applicable bump action");
  }
  const pkg = action.package;
  const to = action.to;

  const repoInfo = (await gh(token, "GET", `/repos/${owner}/${repo}`)) as { default_branch: string };
  const base = repoInfo.default_branch;
  const baseRef = (await gh(token, "GET", `/repos/${owner}/${repo}/git/ref/heads/${base}`)) as {
    object: { sha: string };
  };
  const branch = `vulnveto/${pkg}-${to}`.replace(/[^a-zA-Z0-9/_.-]/g, "-");

  await gh(token, "POST", `/repos/${owner}/${repo}/git/refs`, {
    ref: `refs/heads/${branch}`,
    sha: baseRef.object.sha,
  });

  // Read package.json from the base branch, bump, write to our branch.
  const file = (await gh(token, "GET", `/repos/${owner}/${repo}/contents/package.json?ref=${base}`)) as {
    sha: string;
    content: string;
  };
  const pkgJson = JSON.parse(Buffer.from(file.content, "base64").toString("utf8")) as {
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  };
  let bumped = false;
  for (const section of ["dependencies", "devDependencies"] as const) {
    if (pkgJson[section]?.[pkg]) {
      pkgJson[section][pkg] = to.startsWith("^") || to.startsWith("~") ? to : `^${to}`;
      bumped = true;
    }
  }
  if (!bumped) throw new Error(`human-gate: ${pkg} not found in package.json dependencies`);

  await gh(token, "PUT", `/repos/${owner}/${repo}/contents/package.json`, {
    message: `vulnveto: bump ${pkg} to ${to} (${finding.id})`,
    content: Buffer.from(JSON.stringify(pkgJson, null, 2) + "\n").toString("base64"),
    sha: file.sha,
    branch,
  });

  const pr = (await gh(token, "POST", `/repos/${owner}/${repo}/pulls`, {
    title: `🔒 vulnveto: bump ${pkg} to ${to}`,
    head: branch,
    base,
    draft: true,
    body: [
      `## vulnveto security fix (draft — needs your review)`,
      ``,
      `**Finding:** ${finding.title}`,
      `**Severity:** ${finding.severity} · **Confidence:** ${finding.confidence}`,
      ``,
      finding.evidence.summary,
      ``,
      `**Fix applied:** ${finding.fix?.description}`,
      ``,
      ...(finding.evidence.references?.map((r) => `- ${r}`) ?? []),
      ``,
      `> Generated by vulnveto. This is a draft — review the diff, run your tests, then mark ready.`,
    ].join("\n"),
  })) as { html_url: string };

  return { findingId: finding.id, prUrl: pr.html_url, branch };
}

/** Bump a local package.json in place (used for local verification, not PRs). */
export function bumpLocalPackageJson(root: string, pkg: string, to: string): boolean {
  const p = join(root, "package.json");
  let json: any;
  try {
    json = JSON.parse(readFileSync(p, "utf8"));
  } catch {
    return false;
  }
  let bumped = false;
  for (const section of ["dependencies", "devDependencies"]) {
    if (json[section]?.[pkg]) {
      json[section][pkg] = `^${to}`;
      bumped = true;
    }
  }
  return bumped;
}
